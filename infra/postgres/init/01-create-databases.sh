#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE shop LOGIN PASSWORD '${SHOP_DB_PASSWORD}';
CREATE DATABASE shop OWNER shop;
REVOKE ALL ON DATABASE shop FROM PUBLIC;

CREATE ROLE payments LOGIN PASSWORD '${PAYMENTS_DB_PASSWORD}';
CREATE DATABASE payments OWNER payments;
REVOKE ALL ON DATABASE payments FROM PUBLIC;
SQL
